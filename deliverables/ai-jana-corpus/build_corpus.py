def font(run, *, size=None, bold=None, color=None):
    run.font.name = "Calibri"
    run._element.get_or_add_rPr().rFonts.set(qn("w:ascii"), "Calibri")
    run._element.get_or_add_rPr().rFonts.set(qn("w:hAnsi"), "Calibri")
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if color is not None:
        run.font.color.rgb = color


def configure(doc):
    section = doc.sections[0]
    section.page_width = Inches(8.5)
    section.page_height = Inches(11)
    section.top_margin = section.bottom_margin = Inches(1)
    section.left_margin = section.right_margin = Inches(1)
    for name, size, before, after, spacing, color in (
        ("Normal", 11, 0, 6, 1.25, INK),
        ("Heading 1", 16, 18, 10, 1.0, GREEN),
        ("Heading 2", 13, 14, 7, 1.0, GREEN),
    ):
        style = doc.styles[name]
        style.font.name = "Calibri"
        style.font.size = Pt(size)
        style.font.color.rgb = color
        style.font.bold = name != "Normal"
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)
        style.paragraph_format.line_spacing = spacing
        if name != "Normal":
            style.paragraph_format.keep_with_next = True
    header = section.header.paragraphs[0]
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    font(header.add_run("DIGITAL HR  •  DEMO / SYNTHETIC"), size=8, color=MUTED)
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    font(footer.add_run("JanaМен  |  учебный корпус  |  "), size=8, color=MUTED)
    field = OxmlElement("w:fldSimple")
    field.set(qn("w:instr"), "PAGE")
    footer._p.append(field)


def metadata(doc, label, value):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    font(p.add_run(label + ": "), size=9, bold=True, color=MUTED)
    font(p.add_run(value), size=9, color=INK)


def build(item):
    doc = Document()
    configure(doc)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    font(p.add_run(item["id"]), size=10, bold=True, color=GREEN)
    title = doc.add_paragraph(style="Title")
    title.paragraph_format.space_before = Pt(0)
    title.paragraph_format.space_after = Pt(12)
    title.paragraph_format.keep_with_next = True
    font(title.add_run(item["title"]), size=22, bold=True, color=INK)
    for label, value in (
        ("Document ID", item["id"]), ("Version / created", f"1.0 / {date(2026, 10, 17).isoformat()}"),
        ("Category", item["category"]), ("Source classification", item["classification"]),
        ("Intended audience", item["audience"]), ("Access scope", item["scope"]),
    ):
        metadata(doc, label, value)
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(12)
    font(p.add_run("DEMO / SYNTHETIC. "), bold=True, color=GREEN)
    font(p.add_run(item["lead"]))
    for sid, heading, paragraphs in item["sections"]:
        doc.add_heading(f"{item['id']} {sid}  {heading}", level=2)
        for body in paragraphs:
            doc.add_paragraph(body)
    doc.add_heading(f"{item['id']}  Источники и примечания", level=2)
    for line in item["sources"]:
        p = doc.add_paragraph(line)
        p.paragraph_format.space_after = Pt(3)
        for run in p.runs:
            font(run, size=9, color=MUTED)
    doc.core_properties.title = f"{item['id']} — {item['title']}"
    doc.core_properties.subject = "DEMO / SYNTHETIC Digital HR knowledge corpus"
    doc.core_properties.keywords = f"{item['id']}; {item['scope']}; source-aware"
    out = ROOT / f"{item['id']}.docx"
    doc.save(out)
    return out


def main():
    files = [build(item) for item in DOCS]
    with ZipFile(ROOT / "ai-jana-corpus.zip", "w", ZIP_DEFLATED) as archive:
        for path in files:
            archive.write(path, arcname=path.name)
    print("\n".join(str(path) for path in files))


if __name__ == "__main__":
    main()
